void font_draw_char(char c, int x, int y, uint32_t color, uint8_t scale) {
  if (scale == 0) {
    return;
  }

  const uint8_t *pattern = font_get_pattern(c);

  for (uint8_t row = 0; row < FONT_HEIGHT; row++) {
    for (uint8_t col = 0; col < FONT_WIDTH; col++) {
      if (pattern[row] & (1 << (FONT_WIDTH - 1 - col))) {
        int px = x + col * scale;
        int py = y + row * scale;
        graphics_draw_rectangle_clipped(px, py, scale, scale, color);
      }
    }
  }
}

void font_draw_text(const char *text, int x, int y, uint32_t color, uint8_t scale) {
  if (text == 0 || scale == 0) {
    return;
  }

  int current_x = x;
  int advance = (FONT_WIDTH + FONT_SPACING) * scale;

  for (int i = 0; text[i] != '\0'; i++) {
    font_draw_char(text[i], current_x, y, color, scale);
    current_x += advance;
  }
}

int font_text_width(const char *text, uint8_t scale) {
  if (text == 0 || scale == 0) {
    return 0;
  }

  int length = 0;

  while (text[length] != '\0') {
    length++;
  }

  if (length == 0) {
    return 0;
  }

  return (length * FONT_WIDTH + (length - 1) * FONT_SPACING) * scale;
}

void font_draw_text_centered(const char *text, int center_x, int y, uint32_t color, uint8_t scale) {
  if (text == 0 || scale == 0) {
    return;
  }

  int width = font_text_width(text, scale);
  int x = center_x - width / 2;

  font_draw_text(text, x, y, color, scale);
}

void font_draw_number(int number, int x, int y, uint32_t color, uint8_t scale) {
  char buffer[12];
  int index = 0;
  bool negative = false;

  if (scale == 0) {
    return;
  }

  if (number == 0) {
    font_draw_char('0', x, y, color, scale);
    return;
  }

  if (number < 0) {
    negative = true;
    number = -number;
  }

  while (number > 0 && index < 10) {
    buffer[index] = (char) ('0' + (number % 10));
    number /= 10;
    index++;
  }

  if (negative && index < 11) {
    buffer[index] = '-';
    index++;
  }

  int current_x = x;
  int advance = (FONT_WIDTH + FONT_SPACING) * scale;

  for (int i = index - 1; i >= 0; i--) {
    font_draw_char(buffer[i], current_x, y, color, scale);
    current_x += advance;
  }
}
