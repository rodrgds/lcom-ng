static const uint8_t FONT_UNKNOWN[7] = {
  0x0E,
  0x11,
  0x01,
  0x02,
  0x04,
  0x00,
  0x04
};

static const uint8_t FONT_SPACE[7] = {
  0x00,
  0x00,
  0x00,
  0x00,
  0x00,
  0x00,
  0x00
};

