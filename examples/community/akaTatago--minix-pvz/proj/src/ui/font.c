#define CHAR_W 5
#define CHAR_H 7
#define SCALE  2
#define SPACING 2

void font_draw_char(char c, int x, int y, uint32_t color) {
    uint8_t idx = (uint8_t) c;
    if (idx >= 128) return;
    const uint8_t *bmp = font_data[idx];
    for (int row = 0; row < CHAR_H; row++) {
        uint8_t bits = bmp[row];
        for (int col = 0; col < CHAR_W; col++) {
            if (bits & (1 << (CHAR_W - 1 - col))) {
                vg_draw_rectangle(x + col * SCALE, y + row * SCALE, SCALE, SCALE, color);
            }
        }
    }
}

void font_draw_string(const char *str, int x, int y, uint32_t color) {
    int cx = x;
    while (*str) {
        font_draw_char(*str, cx, y, color);
        cx += CHAR_W * SCALE + SPACING;
        str++;
    }
}

void font_draw_number(int num, int x, int y, uint32_t color) {
    if (num < 0) {
        font_draw_char('-', x, y, color);
        x += CHAR_W * SCALE + SPACING;
        num = -num;
    }
    if (num == 0) { font_draw_char('0', x, y, color); return; }
    char buf[12];
    int len = 0;
    int tmp = num;
    while (tmp > 0) { buf[len++] = '0' + (tmp % 10); tmp /= 10; }
    for (int i = len - 1; i >= 0; i--) {
        font_draw_char(buf[i], x, y, color);
        x += CHAR_W * SCALE + SPACING;
    }
}
