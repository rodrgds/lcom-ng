int (map_get_terminal_positions) (struct point2D terminals[]) {
  int i = 0;
  for (int y = 0; y < 24; y++) {
    for (int x = 0; x < 32; x++) {
      if (grid[y][x] == 3) {
        terminals[i].x = x;
        terminals[i].y = y;
        i++;
      }
    }
  }
  return i;
}

int (map_get_door_position) (struct point2D* door) {
  for (int y = 0; y < 24; y++) {
    for (int x = 0; x < 32; x++) {
      if (grid[y][x] == 8) {
        door->x = x;
        door->y = y;
        break;
      }
    }
  }
  return 0;
}
