#!/usr/bin/env python3
"""Generate 8 directions x 3 silhouette-relative offsets from the game's XPMs."""

import argparse
import ast
import math
from pathlib import Path
import re

PROJ = Path(__file__).resolve().parents[1]
OUTPUT = PROJ / "assets/sushi_pieces/cut_profiles.h"


def read_xpm(path):
    strings = [ast.literal_eval(value) for value in re.findall(r'"(?:[^"\\]|\\.)*"', path.read_text())]
    width, height, colors, cpp = map(int, strings[0].split())
    if min(width, height, colors, cpp) <= 0 or len(strings) != 1 + colors + height:
        raise ValueError(f"{path}: invalid XPM dimensions or row count")
    palette = {}
    for entry in strings[1:1 + colors]:
        match = re.fullmatch(r"\s+c\s+(None|#[0-9a-fA-F]{6})\s*", entry[cpp:])
        if not match or entry[:cpp] in palette:
            raise ValueError(f"{path}: invalid or duplicate palette entry")
        palette[entry[:cpp]] = match[1]
    rows = strings[1 + colors:]
    if any(len(row) != width * cpp for row in rows):
        raise ValueError(f"{path}: invalid row width")
    pixels = []
    for y, row in enumerate(rows):
        for x in range(width):
            color = palette[row[x * cpp:(x + 1) * cpp]]
            if color.lower() != "none":
                pixels.append((x + 0.5 - width / 2, y + 0.5 - height / 2))
    if not pixels:
        raise ValueError(f"{path}: empty silhouette")
    return width, height, pixels


def generate():
    source = (PROJ / "src/sushi.c").read_text()
    table = re.search(r"sushi_xpms\[[^]]*\]\s*=\s*\{(.*?)\};", source, re.S)
    names = re.findall(r"\(xpm_map_t\)(\w+)_xpm", table[1])
    if not names or len(names) != len(set(names)):
        raise ValueError("invalid sushi_xpms table")
    lines = ["/* Generated by proj/tools/generate_cut_profiles.py; do not edit. */",
             "#ifndef SUSHI_CUT_PROFILES_H", "#define SUSHI_CUT_PROFILES_H", "",
             '#include "../../include/game/cut_profile.h"', "",
             "static const cut_profile_set_t sushi_cut_profiles[] = {"]
    for name in names:
        width, height, pixels = read_xpm(PROJ / f"assets/sushi_pieces/{name}.xpm")
        lines.append(f"    /* {name} */\n    {{{width}, {height}, {{")
        for direction in range(8):
            angle = direction * math.pi / 8
            nx, ny = -math.sin(angle), math.cos(angle)
            projections = [nx * x + ny * y for x, y in pixels]
            low, high = min(projections), max(projections)
            for fraction in (0.25, 0.5, 0.75):
                offset = low + (high - low) * fraction
                nx_out, ny_out, offset_out = (float(f"{v:.9f}") for v in (nx, ny, offset))
                # Check the rounded values that C will actually use.
                sides = [nx_out * x + ny_out * y < offset_out for x, y in pixels]
                assert any(sides) and not all(sides), f"{name}: empty cut side"
                lines.append(f"        {{{nx_out:.9f}, {ny_out:.9f}, {offset_out:.9f}}},")
        lines.append("    }},")
    lines.extend(["};", "", "#endif", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify the checked-in profiles are current")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != generated:
            raise SystemExit("Cut profiles are stale; run python3 proj/tools/generate_cut_profiles.py")
    else:
        OUTPUT.write_text(generated)
    print("Checked" if args.check else "Generated", OUTPUT.relative_to(PROJ.parent))


if __name__ == "__main__":
    main()
