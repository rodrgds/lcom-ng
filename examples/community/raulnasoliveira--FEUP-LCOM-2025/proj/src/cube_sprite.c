Sprite *create_cube_sprite(int x, int y, int xspeed, int yspeed, double rotation_speed) {
    Sprite *sp = (Sprite *) malloc(sizeof(Sprite));
    if (sp == NULL) return NULL;
    
    xpm_image_t img;
    sp->map = xpm_load(cube_pixmaps[0], XPM_8_8_8, &img);
    if (sp->map == NULL) {
        free(sp);
        return NULL;
    }
    
    sp->x = x;
    sp->y = y;
    sp->width = img.width;
    sp->height = img.height;
    sp->xspeed = xspeed;
    sp->yspeed = yspeed;
    sp->angle = 0;
    sp->rotation_speed = rotation_speed;
    
    return sp;
}

void update_cube_sprite(Sprite *sp) {
    sp->x += sp->xspeed;
    sp->y += sp->yspeed;
    
    if (sp->x > information.XResolution) sp->x = -sp->width;
    if (sp->x < -sp->width) sp->x = information.XResolution;
    if (sp->y > information.YResolution) sp->y = -sp->height;
    if (sp->y < -sp->height) sp->y = information.YResolution;
    
    sp->angle += sp->rotation_speed;
    if (sp->angle >= 2*M_PI) sp->angle -= 2*M_PI;
}

void draw_cube_sprite(Sprite *sp, uint8_t* buffer) {
    int frame = (int)(sp->angle / (M_PI/4)) % 8;
    
    xpm_image_t img;
    uint8_t *pixmap = xpm_load(cube_pixmaps[frame], XPM_8_8_8, &img);
    if (pixmap == NULL) return;
    
    for (int h = 0; h < img.height; h++) {
        for (int w = 0; w < img.width; w++) {
            int idx = (h*img.width+w)*3;
            uint8_t b = pixmap[idx];
            uint8_t g = pixmap[idx+1];
            uint8_t r = pixmap[idx+2];
            uint32_t color = direct_mode(r,g,b);
            if(r==0 && g==0 && b==0) {
                continue;
            }
            if (color != 0) {
                vg_draw_pixel_buffer(buffer, sp->x+w, sp->y + h, color);
            }
        }
    }
    
    free(pixmap);
}

Sprite *create_letter_sprite(const char **letter_xpm, int x, int y) {
    Sprite *sp = (Sprite *) malloc(sizeof(Sprite));
    if (sp == NULL) return NULL;

    xpm_image_t img;
    sp->map = xpm_load(letter_xpm, XPM_8_8_8, &img);
    if (sp->map == NULL) {
        free(sp);
        return NULL;
    }

    sp->x = x;
    sp->y = y;
    sp->width = img.width;
    sp->height = img.height;
    sp->xspeed = 0;       
    sp->yspeed = 0;
    sp->angle = 0;       
    sp->rotation_speed = 0;

    return sp;
}

void draw_xpm_letter(const char **xpm, int x, int y, uint8_t *buffer) {
    xpm_image_t img;
    uint8_t *pixmap = xpm_load(xpm, XPM_8_8_8, &img);
    if (pixmap == NULL) return;

    for (int h = 0; h < img.height; h++) {
        for (int w = 0; w < img.width; w++) {
            int idx = (h*img.width+w)*3;
            uint8_t b = pixmap[idx];
            uint8_t g = pixmap[idx+1];
            uint8_t r = pixmap[idx+2];
            uint32_t color = direct_mode(r,g,b);
            if(r==0 && g==0 && b==0) {
                continue;
            }
            if (color != 0) {
                vg_draw_pixel_buffer(buffer, x + w, y + h, color);
            }
        }
    }
    free(pixmap);
}

void destroy_sprite(Sprite *sp) {
    if (sp == NULL) return;
    if (sp->map) free(sp->map);
    free(sp);
}
