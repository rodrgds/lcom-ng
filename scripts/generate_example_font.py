#!/usr/bin/env python3
"""Bake 4-bit UI glyphs. Requires Pillow and a DejaVuSans.ttf argument.

This generation step uses a font library. The committed tables keep all C
examples self-contained, including installed/relocated SDK builds.
"""
from pathlib import Path
import sys
from PIL import Image, ImageDraw, ImageFont

if len(sys.argv) != 2:
    raise SystemExit('usage: generate_example_font.py /path/to/DejaVuSans.ttf')
font_path = Path(sys.argv[1])
output = ['/* Generated by scripts/generate_example_font.py. See example-font-LICENSE.txt. */',
          '#ifndef LCOM_EXAMPLE_FONT_H', '#define LCOM_EXAMPLE_FONT_H']
for name, filename, width in [('ui', 'DejaVuSans.ttf', 16),
                              ('bold', 'DejaVuSans-Bold.ttf', 16),
                              ('mono', 'DejaVuSansMono.ttf', 9)]:
    font = ImageFont.truetype(str(font_path.with_name(filename)), 14)
    output.append(f'static const uint8_t example_{name}_advance[95] = {{' +
                  ','.join(str(round(font.getlength(chr(c)))) for c in range(32, 127)) + '};')
    if name == 'bold':
        continue  # Headings use the full-size atlas below.
    output.append(f'static const uint64_t example_{name}_rows[95][18] = {{')
    for code in range(32, 127):
        glyph = Image.new('L', (width, 18))
        ImageDraw.Draw(glyph).text((0, -1), chr(code), font=font, fill=255)
        rows = [sum(round(glyph.getpixel((x, y)) / 17) << ((width - 1 - x) * 4)
                    for x in range(width)) for y in range(18)]
        output.append('  {' + ','.join(f'UINT64_C(0x{x:x})' for x in rows) + '},')
    output.append('};')
# Bake headings at 28px so large text has native coverage, rather than enlarged
# 14px pixels. Keep the existing doubled advances to preserve app layout.
font = ImageFont.truetype(str(font_path.with_name('DejaVuSans-Bold.ttf')), 28)
output.append('static const uint8_t example_heading_pixels[95][36][16] = {')
for code in range(32, 127):
    glyph = Image.new('L', (32, 36))
    ImageDraw.Draw(glyph).text((0, -2), chr(code), font=font, fill=255)
    output.append('  {')
    for y in range(36):
        values = [(round(glyph.getpixel((x, y)) / 17) << 4) | round(glyph.getpixel((x + 1, y)) / 17) for x in range(0, 32, 2)]
        output.append('    {' + ','.join(f'0x{value:02x}' for value in values) + '},')
    output.append('  },')
output.append('};')
# Render timer numerals at their actual display size, without scaling tiny labels.
font = ImageFont.truetype(str(font_path.with_name('DejaVuSansMono-Bold.ttf')), 96)
output.append('static const uint8_t example_number_pixels[14][80][29] = {')
for character in '0123456789:.- ':
    glyph = Image.new('L', (58, 80))
    ImageDraw.Draw(glyph).text((0, -16), character, font=font, fill=255)
    output.append('  {')
    for y in range(80):
        values = [(round(glyph.getpixel((x, y)) / 17) << 4) | round(glyph.getpixel((x + 1, y)) / 17) for x in range(0, 58, 2)]
        output.append('    {' + ','.join(f'0x{value:02x}' for value in values) + '},')
    output.append('  },')
output.append('};')
output.extend(['#endif', ''])
Path('examples/example_font.h').write_text('\n'.join(output))

# Native export controls share the same licensed UI and mono glyphs.
source = '\n'.join(output)
a = source.index('static const uint8_t example_ui_advance')
b = source.index('static const uint8_t example_bold_advance')
c = source.index('static const uint8_t example_mono_advance')
d = source.index('static const uint8_t example_heading_pixels')
Path('runtime/embedded/ControlFont.hpp').write_text(
    '// Generated by scripts/generate_example_font.py. See ControlFont-LICENSE.txt.\n'
    '#pragma once\n#include <cstdint>\nnamespace lcom::embedded::font {\n'
    + (source[a:b] + source[c:d]).replace('example_', '') + '}\n')
